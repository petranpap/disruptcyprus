<p>Disrupt Cyprus covers startups and innovation in Cyprus and the Eastern Mediterranean: funding rounds, founders, research, policy and the events where the ecosystem meets.</p>
<p>Every story is written and edited by our own team. We don't aggregate other outlets or republish feeds, and no algorithm decides what counts as news. Personalization only changes the order: you follow the industries you care about, and your feed, briefings and alerts follow them too.</p>
<h2>What you get</h2>
<ul>
    <li>A personalized feed across 33 industries, from FinTech and AI to Maritime and AgriTech.</li>
    <li>Daily and monthly news briefings, and weekly and monthly event roundups, delivered at the time you choose.</li>
    <li>An events calendar with reminders for the events you save.</li>
    <li>Offline reading for saved stories, in Greek and English.</li>
</ul>
