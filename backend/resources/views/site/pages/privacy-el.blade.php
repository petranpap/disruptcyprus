<h2>Πόσο καιρό τα διατηρούμε</h2>
<p>Διατηρούμε τα δεδομένα σου όσο έχεις λογαριασμό. Όταν διαγράφεις τον λογαριασμό σου, αφαιρούμε αμέσως το προφίλ, τις προτιμήσεις, τα αποθηκευμένα, τις ειδοποιήσεις και τις συσκευές σου, και ανωνυμοποιούμε την εγγραφή του λογαριασμού. Η ανωνυμοποιημένη εγγραφή διαγράφεται οριστικά μετά από 30 ημέρες. Τα αντίγραφα ασφαλείας της βάσης δεδομένων διατηρούνται έως 14 ημέρες.</p>

