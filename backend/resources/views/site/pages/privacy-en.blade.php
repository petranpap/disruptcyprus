<p>This policy explains what personal data Disrupt Cyprus ("we") processes when you use disruptcyprus.com and app.disruptcyprus.com, why, and what you can do about it. Contact: <a href="mailto:privacy@disruptcyprus.com">privacy@disruptcyprus.com</a>.</p>

<h2>What we collect</h2>
<ul>
    <li><strong>Account:</strong> your name, email address, password (stored only as a one-way hash) or, if you sign in with Google, your Google account ID and email. Optionally a profile photo.</li>
    <li><strong>Preferences:</strong> language, the industries you follow, which briefings and reminders you want, your delivery time and timezone.</li>
    <li><strong>Activity you choose to save:</strong> saved stories and events, and the notifications we have sent you.</li>
    <li><strong>Push notifications:</strong> if you turn them on, the address your browser gives us for delivering notifications to that device, and the browser name.</li>
    <li><strong>Reading statistics:</strong> we count how often stories are read using a daily, one-way hash of the IP address and browser. We cannot link these counts to you.</li>
    <li><strong>Launch waitlist:</strong> if you join it on our coming-soon page, your name, email and language, to send you one email when we launch. We keep them until then and delete them on request.</li>
    <li><strong>Server logs:</strong> IP address, time and requested page, kept for security and troubleshooting.</li>
</ul>
<p>We do not use advertising or analytics trackers, and we do not sell or share your data for marketing.</p>

<h2>Why, and on what legal basis</h2>
<ul>
    <li>To provide the service you signed up for: your account, personalized feed, briefings and saved items (performance of a contract, GDPR Art. 6(1)(b)).</li>
    <li>To send the launch email to people on the waitlist (consent, Art. 6(1)(a)).</li>
    <li>To send push notifications, only after you allow them in your browser (consent, Art. 6(1)(a)). You can turn them off at any time in Settings or in your browser.</li>
    <li>To keep the service secure and working (legitimate interests, Art. 6(1)(f)).</li>
</ul>

<h2>Cookies</h2>
<p>We only use strictly necessary cookies: a session cookie that keeps you signed in and a security token that protects forms. The public pages on disruptcyprus.com set no cookies. Language, theme and similar settings are stored in your browser's local storage.</p>

<h2>Who processes data for us</h2>
<ul>
    <li>Hosting: Hetzner Online GmbH, servers in the European Union.</li>
    <li>Email delivery: our email provider, for sign-up, password and data-export emails.</li>
    <li>Google, only if you choose "Continue with Google".</li>
    <li>Your browser's push service (for example Google, Mozilla, Apple or Microsoft), which receives the encrypted notification and delivers it to your device.</li>
</ul>

<h2>How long we keep it</h2>
<p>We keep your data while you have an account. When you delete your account, we immediately remove your profile, preferences, saved items, notifications and devices, and anonymize the account record. The anonymized record is permanently deleted after 30 days. Database backups are kept for up to 14 days.</p>

<h2>Your rights</h2>
<p>You can access, correct, export and delete your data. Download a copy or delete your account at any time in Settings → Privacy in the app. You can also object to processing, ask us to restrict it, or withdraw consent. To exercise any right, email us. You may complain to the Commissioner for Personal Data Protection in Cyprus (<a href="https://www.dataprotection.gov.cy" rel="noopener">dataprotection.gov.cy</a>).</p>

<h2>Children</h2>
<p>Disrupt Cyprus is not intended for children under 16.</p>

<h2>Changes</h2>
<p>If we change this policy, we will update the date above and, for significant changes, tell signed-in readers in the app.</p>
